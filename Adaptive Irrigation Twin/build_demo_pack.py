"""Build a clearly labelled demo dataset from the bundled AquaCrop example output."""
from __future__ import annotations
import csv
import json
from pathlib import Path
import zipfile

app = Path(__file__).resolve().parent
demo = app / "demo_data"
demo.mkdir(exist_ok=True)
scenario_dir = app / "scenario_outputs_oct15"
baseline = scenario_dir / "irrigation_0mm_1996-10-15.csv"
with baseline.open(encoding="utf-8", newline="") as f:
    model_rows = list(csv.DictReader(f))

weather_fields = ["date", "source", "tmin_c", "tmax_c", "rain_mm", "eto_mm"]
weather = []
for row in model_rows:
    weather.append({
        "date": row["date"], "source": "seasonal", "tmin_c": row["Tmin"],
        "tmax_c": row["Tmax"], "rain_mm": row["Rain"], "eto_mm": row["ETo"],
    })
with (demo / "weather_demo.csv").open("w", encoding="utf-8", newline="") as f:
    w = csv.DictWriter(f, fieldnames=weather_fields)
    w.writeheader(); w.writerows(weather)

by_date = {r["date"]: r for r in weather}
moisture = [31.8, 31.2, 30.7, 30.1, 29.6, 29.2, 30.0, 29.5, 28.9, 28.4]
obs_fields = ["timestamp", "field_id", "sensor_id", "depth_cm", "soil_moisture_pct", "tmin_c", "tmax_c", "rain_mm", "eto_mm", "irrigation_mm", "crop_stage", "notes"]
observations = []
for i, day in enumerate(range(10, 20)):
    date = f"1996-10-{day:02d}"
    wx = by_date[date]
    observations.append({
        "timestamp": f"{date}T08:00:00", "field_id": "DEMO-PAT-01", "sensor_id": "DEMO-SM-30CM",
        "depth_cm": 30, "soil_moisture_pct": moisture[i], "tmin_c": wx["tmin_c"], "tmax_c": wx["tmax_c"],
        "rain_mm": wx["rain_mm"], "eto_mm": wx["eto_mm"], "irrigation_mm": 5 if date == "1996-10-15" else 0,
        "crop_stage": "Mid-season (demo label)", "notes": "SYNTHETIC TRAINING VALUE — not a real sensor observation",
    })
with (demo / "observations_demo.csv").open("w", encoding="utf-8", newline="") as f:
    w = csv.DictWriter(f, fieldnames=obs_fields)
    w.writeheader(); w.writerows(observations)

profile = {
    "profile": {
        "fieldId": "DEMO-PAT-01", "location": "Patancheru, Telangana, India (illustrative case)",
        "crop": "Maize", "planting": "1996-07-01", "seasonEnd": "1996-11-09", "area": "1.0",
        "soil": "Loam (example profile)", "rootDepth": "1.2",
        "weatherSource": "Historical AquaCrop example weather — demo only",
    },
    "settings": {"stressLimit": "5", "waterLimit": "100"},
    "scenarios": [
        {"name": f"One event — {mm} mm", "date": "1996-10-15", "amount": str(mm)}
        for mm in (0, 5, 10, 15, 20)
    ],
}
(demo / "field_setup_and_scenarios.json").write_text(json.dumps(profile, indent=2), encoding="utf-8")

scenario_fields = ["name", "date", "amount_mm", "description"]
with (demo / "scenario_plan.csv").open("w", encoding="utf-8", newline="") as f:
    w = csv.DictWriter(f, fieldnames=scenario_fields)
    w.writeheader()
    for mm in (0, 5, 10, 15, 20):
        w.writerow({"name": f"One event — {mm} mm", "date": "1996-10-15", "amount_mm": mm,
                    "description": "Synthetic comparison plan; actual AquaCrop outputs are in scenario_outputs/"})

readme = """# Demo data pack\n\nUse this dataset to check the local app's profile entry, CSV imports, season coverage, scenario list, and AquaCrop comparison viewer. It is for software demonstration only.\n\n## What's real and what's synthetic\n\n- `weather_demo.csv` contains the daily Tmin, Tmax, rain, and ETo from the historical Patancheru example included with AquaCrop. Every row is marked `seasonal` so the app does not present it as current observed weather.\n- `observations_demo.csv` contains 10 invented sensor records. Each row is explicitly flagged as synthetic in `notes`; these are not field measurements.\n- `field_setup_and_scenarios.json` gives profile values and the five irrigation scenarios. The app has no JSON import for profile/scenarios yet, so enter those values in the corresponding forms.\n- `scenario_outputs/` contains the five daily and seasonal outputs generated by actual AquaCrop 7.3 runs, each with one 0/5/10/15/20 mm event on 1996-10-15.\n\n## Load into the app\n\n1. Open `index.html`. Use the values under `profile` in `field_setup_and_scenarios.json` to fill the Field profile, then save it.\n2. Import `observations_demo.csv` in Field observation input. The table should show 10 synthetic records.\n3. Import `weather_demo.csv` under Daily weather timeline. Coverage should read complete: 132 / 132 days, July 1 to November 9, 1996.\n4. Add the five rows from the JSON `scenarios` array in the scenario form.\n5. Open `visualization.html`, import the five daily CSVs from `scenario_outputs/`, and select two scenario names to compare. Repeat with other pairs.\n\nThe example's full-season rainfall is high enough that all five runs have the same final yield. Root-zone water differs on the irrigation event day. No recommendation is produced from these demo values.\n"""
if not (demo / "README.md").exists():
    (demo / "README.md").write_text(readme, encoding="utf-8")

zip_path = app / "irrigation_digital_twin_demo_pack.zip"
with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
    for p in sorted(demo.iterdir()):
        z.write(p, Path("demo_data") / p.name)
    for p in sorted(scenario_dir.glob("*")):
        z.write(p, Path("demo_data") / "scenario_outputs" / p.name)
print(f"Created {zip_path} with {len(weather)} weather days, {len(observations)} synthetic observations, and 5 AquaCrop scenarios.")
